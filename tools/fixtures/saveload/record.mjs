// Record the independent headless expectation for the Save/Load fixture (ticket #934, plan AC2).
//
//   node tools/fixtures/saveload/record.mjs [--check]
//
// Drives the authored Save/Load fixture through the real engine with the harness's `runSaveLoadFixture` over an
// in-memory blob host, recording:
//   * the `saveBlob` request key, path and byte length;
//   * the `loadBlob` request key, path and found flag;
//   * the fresh-game, pre-Save, post-Load and final state hashes with their ticks;
//   * the `GameId` derived from the package's content digest and main file.
//
// The expectation is bound to `saveload.tpk` by its SHA-256 digest, so `generate.mjs --check` fails when the fixture
// drifts and was not re-recorded. This script imports the compiled `@tk-reawakened/runner-harness` and `@tk-reawakened/core`
// (dist), never `src/` directly (guard-rail G2).

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { readZip } from "@tk-reawakened/core";
import { createMemoryBlobHost, runSaveLoadFixture } from "@tk-reawakened/runner-harness";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "../../..");
const fixtureDir = join(repoRoot, "packages", "core", "test", "fixtures", "saveload");
const tpkPath = join(fixtureDir, "saveload.tpk");
const expectPath = join(fixtureDir, "saveload.expect.json");

const tpkBytes = readFileSync(tpkPath);
const unzipped = readZip(tpkBytes, "saveload.tpk");
if (!unzipped.ok) throw new Error(unzipped.error.message);
const files = new Map();
for (const entry of unzipped.value) files.set(entry.path, entry.bytes);

const host = createMemoryBlobHost();
const run = await runSaveLoadFixture({ files, host });

const sha256 = createHash("sha256").update(tpkBytes).digest("hex");
const record = {
  schema: 1,
  comment: "Independent headless baseline expectation for the Save/Load fixture (ticket #934, plan AC2). Generated by tools/fixtures/saveload/record.mjs using the real engine and runner-harness. Bound to saveload.tpk by its SHA-256; --check fails when the fixture drifts.",
  fixture: {
    package: "saveload.tpk",
    sha256,
    size: tpkBytes.length,
    gameId: run.gameId,
  },
  baseline: {
    saveRequest: run.saveRequest,
    loadRequest: run.loadRequest,
    stateHashes: {
      fresh: { tick: run.saved.fresh.tick, stateHash: run.saved.fresh.stateHash },
      preSave: { tick: run.saved.preSave?.tick ?? 0, stateHash: run.saved.preSave?.stateHash ?? "" },
      postLoad: { tick: run.loaded.postLoad?.tick ?? 0, stateHash: run.loaded.postLoad?.stateHash ?? "" },
      final: { tick: run.tick, stateHash: run.finalStateHash },
    },
    tick: run.tick,
  },
};

const checkOnly = process.argv.includes("--check");
if (checkOnly) {
  let disk;
  try { disk = JSON.parse(readFileSync(expectPath, "utf8")); } catch { console.error("record.mjs: saveload.expect.json missing or not JSON"); process.exit(1); }
  const actualJson = JSON.stringify(record, null, 2);
  const diskJson = JSON.stringify(disk, null, 2);
  if (actualJson !== diskJson) {
    console.error("record.mjs: saveload.expect.json differs from a fresh headless run (re-run `pnpm saveload:record`)");
    process.exit(1);
  }
  console.log("saveload.expect.json matches fresh headless baseline");
  process.exit(0);
}

writeFileSync(expectPath, `${JSON.stringify(record, null, 2)}\n`);
console.log(`wrote ${expectPath} for ${run.gameId} (${run.saveRequest.byteLength} save bytes, post-load hash ${record.baseline.stateHashes.postLoad.stateHash})`);
