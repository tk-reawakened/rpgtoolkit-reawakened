import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const toolingPath = resolve(root, "docs/spec/engine/rpgcode-tooling.md");
const savingPath = resolve(root, "docs/help/saving.md");
const changelogPath = resolve(root, "CHANGELOG.md");
const outputPath = resolve(root, "packages/editor-ui/src/help-content.generated.ts");

function authoringGuide(markdown) {
  const lines = markdown.split(/\r?\n/);
  const start = lines.findIndex((line) => line === '<a id="tool-10"></a>');
  if (start < 0) throw new Error(`Missing TOOL-10 anchor in ${toolingPath}`);
  const selected = [];
  const wanted = [
    /^\*\*TOOL-10 Program editing/,
    /^- \*\*Navigation \(bookmarks\)\./,
    /^- \*\*Call tips\*\*/,
    /^- \*\*Command reference and insertion\./,
    /^- \*\*Header template\./,
    /^- \*\*Distraction-free mode\*/,
    /^- \*\*Failure\./,
    /^- \*\*VS Code extensions\./,
  ];
  let active = false;
  for (const line of lines.slice(start)) {
    if (line.startsWith('<a id="tool-10-') && line !== '<a id="tool-10"></a>') continue;
    if (wanted.some((pattern) => pattern.test(line))) {
      active = true;
      selected.push(line);
      continue;
    }
    if (active && (line.startsWith("- ") || line.startsWith("<a id=") || line.startsWith("<!--"))) active = false;
    if (active && line.trim() !== "") selected.push(line);
  }
  const content = selected.join("\n").trim();
  if (content.length === 0) throw new Error(`TOOL-10 authoring content is empty in ${toolingPath}`);
  return `# RPGCode program authoring\n\n${content}\n\nThis guide is drawn from the repository's TOOL-10 editor specification. It is a maintained authoring reference, not the legacy HTML manual.`;
}

function unreleasedNotes(markdown) {
  const lines = markdown.split(/\r?\n/);
  if (lines[0] !== "# Changelog") throw new Error(`Unexpected changelog heading in ${changelogPath}`);
  if (lines[2] !== "## Unreleased") throw new Error(`Missing Unreleased section in ${changelogPath}`);
  const nextHeading = lines.findIndex((line, index) => index > 2 && /^## /.test(line));
  const notes = lines.slice(3, nextHeading < 0 ? undefined : nextHeading).filter((line) => line.startsWith("- "));
  if (notes.length === 0) throw new Error(`Missing non-empty Unreleased section in ${changelogPath}`);
  return `# What's New\n\n${notes.slice(0, 12).join("\n\n")}\n\n[Read the full changelog](https://github.com/tk-reawakened/rpgtoolkit-reawakened/blob/main/CHANGELOG.md).`;
}

const tooling = readFileSync(toolingPath, "utf8");
const changelog = readFileSync(changelogPath, "utf8");
const saving = readFileSync(savingPath, "utf8");
const output = `// Generated by tools/editor-ui-toolchain/generate-help-content.mjs. Do not edit by hand.\nexport const AUTHORING_GUIDE_MARKDOWN = ${JSON.stringify(authoringGuide(tooling))};\nexport const SAVING_HELP_MARKDOWN = ${JSON.stringify(saving)};\nexport const WHATS_NEW_MARKDOWN = ${JSON.stringify(unreleasedNotes(changelog))};\n`;

if (process.argv.includes("--check")) {
  let existing;
  try {
    existing = readFileSync(outputPath, "utf8");
  } catch {
    existing = "";
  }
  if (existing !== output) {
    console.error("Generated editor help is stale; run pnpm help-content:generate.");
    process.exitCode = 1;
  }
} else {
  writeFileSync(outputPath, output);
}
